"""PPO- and fixed-control-authenticated adaptive RL outer evidence.

V2 proves that PPO traces came from the fold-bound frozen actor and frozen
target cost replays.  V3 additionally proves that the comparator trace came
from the fit-selected FC06 action on the exact same sealed outer environment.
"""

from __future__ import annotations

