from dataclasses import dataclass
from pathlib import Path

from rl_quant.evaluation.massive_adaptive_rl_fixed_control_outer_rollout_v1 import (
    MassiveAdaptiveRLFixedControlOuterRolloutAuthorityV1,
)
from rl_quant.evaluation.massive_adaptive_rl_outer_evidence_v2 import (
    MassiveAdaptiveAuthenticatedRLOuterFoldV2,
    MassiveAdaptiveRLOuterEvidenceV2,
    build_massive_adaptive_rl_outer_evidence_v2,
)
from rl_quant.evaluation.massive_adaptive_rl_outer_rollout_v1 import (
    MassiveAdaptiveRLOuterRolloutAuthorityV1,
)
from rl_quant.evaluation.massive_adaptive_rl_outer_plan_v2 import (
    MassiveAdaptiveRLOuterPlanV2,
)
from rl_quant.protocol.canonical_artifact import file_sha256, semantic_sha256
from rl_quant.protocol.massive_adaptive_alpha_v1 import (
    MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256,
    assert_no_adaptive_hold_semantics,
)


MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V3_SCHEMA = (
    "rl-quant.massive-adaptive-authenticated-rl-outer-fold-v3"
)
MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SCHEMA = (
    "rl-quant.massive-adaptive-rl-outer-evidence-v3"
)
MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SOURCE_SHA256 = file_sha256(Path(__file__))
MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SPEC_SHA256 = semantic_sha256(
    {
        "ppo_primary_and_stress": "authenticated-outer-fold-v2",
        "fixed_control": "fit-selection-authenticated-FC06-outer-rollout-v1",
        "outer_plan": "comparator-frozen-before-outer-access-v2",
        "market_context": "same-environment-source-inventory-and-dates",
        "caller_fixed_trace": False,
        "profitability_reporting": False,
        "duration_semantics": False,
    }
)


class MassiveAdaptiveRLOuterEvidenceV3Error(ValueError):
    """The FC06 outer comparator was not generated by its fit selection."""


def _digest(name: str, value: object) -> str:
    if (
        not isinstance(value, str)
        or len(value) != 64
        or any(character not in "0123456789abcdef" for character in value)
    ):
        raise MassiveAdaptiveRLOuterEvidenceV3Error(
            f"{name} must be a lowercase SHA-256"
        )
    return value


@dataclass(frozen=True, slots=True)
class MassiveAdaptiveAuthenticatedRLOuterFoldV3:
    fold_index: int
    authenticated_fold_v2: MassiveAdaptiveAuthenticatedRLOuterFoldV2
    outer_plan_v2_receipt_sha256: str
    fixed_control_outer_authority_receipt_sha256: str
    fixed_control_outer_rollout_receipt_sha256: str
    fixed_control_fit_authority_receipt_sha256: str
    fixed_control_selection_authority_receipt_sha256: str
    fixed_control_policy_trace_receipt_sha256: str
    shared_environment_source_inventory_sha256: str
    fixed_control_outer_source_data_qualified: bool
    source_data_qualified: bool
    semantic_receipt_sha256: str
    protocol_receipt_sha256: str = MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256
    schema: str = MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V3_SCHEMA

    def semantic_unsigned(self) -> dict[str, object]:
        return {
            "schema": self.schema,
            "fold_index": self.fold_index,
            "authenticated_fold_v2_receipt_sha256": (
                self.authenticated_fold_v2.semantic_receipt_sha256
            ),
            "outer_plan_v2_receipt_sha256": self.outer_plan_v2_receipt_sha256,
            "fixed_control_outer_authority_receipt_sha256": (
                self.fixed_control_outer_authority_receipt_sha256
            ),
            "fixed_control_outer_rollout_receipt_sha256": (
                self.fixed_control_outer_rollout_receipt_sha256
            ),
            "fixed_control_fit_authority_receipt_sha256": (
                self.fixed_control_fit_authority_receipt_sha256
            ),
            "fixed_control_selection_authority_receipt_sha256": (
                self.fixed_control_selection_authority_receipt_sha256
            ),
            "fixed_control_policy_trace_receipt_sha256": (
                self.fixed_control_policy_trace_receipt_sha256
            ),
            "shared_environment_source_inventory_sha256": (
                self.shared_environment_source_inventory_sha256
            ),
            "fixed_control_outer_source_data_qualified": (
                self.fixed_control_outer_source_data_qualified
            ),
            "source_data_qualified": self.source_data_qualified,
            "protocol_receipt_sha256": self.protocol_receipt_sha256,
        }

    def validate(self) -> None:
        self.authenticated_fold_v2.validate()
        if (
            self.schema != MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V3_SCHEMA
            or self.fold_index != self.authenticated_fold_v2.fold_index
            or self.fixed_control_policy_trace_receipt_sha256
            != self.authenticated_fold_v2.cost_fold.best_fixed_control_trace_receipt_sha256
            or self.source_data_qualified
            != (
                self.authenticated_fold_v2.source_data_qualified
                and self.fixed_control_outer_source_data_qualified
            )
            or self.semantic_receipt_sha256 != semantic_sha256(self.semantic_unsigned())
        ):
            raise MassiveAdaptiveRLOuterEvidenceV3Error(
                "fixed-control-authenticated outer fold differs"
            )
        for value in (
            self.outer_plan_v2_receipt_sha256,
            self.fixed_control_outer_authority_receipt_sha256,
            self.fixed_control_outer_rollout_receipt_sha256,
            self.fixed_control_fit_authority_receipt_sha256,
            self.fixed_control_selection_authority_receipt_sha256,
            self.fixed_control_policy_trace_receipt_sha256,
            self.shared_environment_source_inventory_sha256,
            self.semantic_receipt_sha256,
        ):
            _digest("fixed-control-authenticated outer fold", value)
        assert_no_adaptive_hold_semantics(self.semantic_unsigned())


def build_massive_adaptive_authenticated_rl_outer_fold_v3(
    *,
    authenticated_fold_v2: MassiveAdaptiveAuthenticatedRLOuterFoldV2,
    outer_plan_v2: MassiveAdaptiveRLOuterPlanV2,
    ppo_outer_rollout_authority: MassiveAdaptiveRLOuterRolloutAuthorityV1,
    fixed_control_outer_authority: (
        MassiveAdaptiveRLFixedControlOuterRolloutAuthorityV1
    ),
) -> MassiveAdaptiveAuthenticatedRLOuterFoldV3:
    """Bind one V2 PPO fold to its replayed fit-selected FC06 comparator."""

    authenticated_fold_v2.validate()
    outer_plan_v2.validate()
    ppo_outer_rollout_authority.validate()
    fixed_control_outer_authority.validate()
    ppo_rollout = ppo_outer_rollout_authority.runtime_rollout
    fixed_rollout = fixed_control_outer_authority.runtime_rollout
    cost_fold = authenticated_fold_v2.cost_fold
    if (
        ppo_rollout is None
        or not ppo_outer_rollout_authority.runtime_rollout_replayed
        or ppo_outer_rollout_authority.semantic_receipt_sha256
        != authenticated_fold_v2.outer_rollout_authority_receipt_sha256
        or ppo_rollout.semantic_receipt_sha256
        != authenticated_fold_v2.outer_rollout_receipt_sha256
        or outer_plan_v2.outer_plan_v1.semantic_receipt_sha256
        != cost_fold.outer_plan_receipt_sha256
        or outer_plan_v2.fold_index != authenticated_fold_v2.fold_index
        or fixed_rollout is None
        or not fixed_control_outer_authority.runtime_rollout_replayed
        or fixed_rollout.fold_index != authenticated_fold_v2.fold_index
        or fixed_rollout.outer_plan_receipt_sha256
        != cost_fold.outer_plan_receipt_sha256
        or fixed_rollout.policy_trace.semantic_receipt_sha256
        != cost_fold.best_fixed_control_trace_receipt_sha256
        or fixed_rollout.policy_trace.evaluation_role != "outer_test"
        or fixed_rollout.policy_trace.transaction_cost_basis_points != 20.0
        or fixed_rollout.policy_trace.frozen_targets_replayed
        or fixed_rollout.fixed_control_fit_authority_receipt_sha256
        != outer_plan_v2.fixed_control_fit_authority_receipt_sha256
        or fixed_rollout.fixed_control_selection_authority_receipt_sha256
        != outer_plan_v2.fixed_control_selection_authority_receipt_sha256
        or fixed_rollout.selected_control_id
        != outer_plan_v2.selected_fixed_control_id
        or fixed_rollout.selected_action_receipt_sha256
        != outer_plan_v2.selected_fixed_action_receipt_sha256
    ):
        raise MassiveAdaptiveRLOuterEvidenceV3Error(
            "outer fixed-control trace is not derived from its fit selection"
        )
    fixed_trace = fixed_rollout.policy_trace
    ppo_trace = ppo_rollout.policy_trace
    if (
        fixed_trace.decision_session_dates != ppo_trace.decision_session_dates
        or fixed_trace.forecast_archive_receipt_sha256
        != ppo_trace.forecast_archive_receipt_sha256
        or fixed_trace.inference_plan_receipt_sha256
        != ppo_trace.inference_plan_receipt_sha256
        or fixed_trace.calibration_receipt_sha256
        != ppo_trace.calibration_receipt_sha256
        or fixed_trace.initial_capital != ppo_trace.initial_capital
        or fixed_rollout.environment_source_inventory_sha256
        != ppo_rollout.environment_source_inventory_sha256
    ):
        raise MassiveAdaptiveRLOuterEvidenceV3Error(
            "outer fixed-control market context differs"
        )
    body = {
        "schema": MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V3_SCHEMA,
        "fold_index": authenticated_fold_v2.fold_index,
        "authenticated_fold_v2": authenticated_fold_v2,
        "outer_plan_v2_receipt_sha256": outer_plan_v2.semantic_receipt_sha256,
        "fixed_control_outer_authority_receipt_sha256": (
            fixed_control_outer_authority.semantic_receipt_sha256
        ),
        "fixed_control_outer_rollout_receipt_sha256": (
            fixed_rollout.semantic_receipt_sha256
        ),
        "fixed_control_fit_authority_receipt_sha256": (
            fixed_rollout.fixed_control_fit_authority_receipt_sha256
        ),
        "fixed_control_selection_authority_receipt_sha256": (
            fixed_rollout.fixed_control_selection_authority_receipt_sha256
        ),
        "fixed_control_policy_trace_receipt_sha256": (
            fixed_trace.semantic_receipt_sha256
        ),
        "shared_environment_source_inventory_sha256": (
            fixed_rollout.environment_source_inventory_sha256
        ),
        "fixed_control_outer_source_data_qualified": (
            fixed_control_outer_authority.outer_evaluation_authorized
        ),
        "source_data_qualified": bool(
            authenticated_fold_v2.source_data_qualified
            and fixed_control_outer_authority.outer_evaluation_authorized
        ),
        "protocol_receipt_sha256": MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256,
    }
    provisional = MassiveAdaptiveAuthenticatedRLOuterFoldV3(
        **body,  # type: ignore[arg-type]
        semantic_receipt_sha256="0" * 64,
    )
    result = MassiveAdaptiveAuthenticatedRLOuterFoldV3(
        **{
            **body,
            "semantic_receipt_sha256": semantic_sha256(provisional.semantic_unsigned()),
        }  # type: ignore[arg-type]
    )
    result.validate()
    return result


@dataclass(frozen=True, slots=True)
class MassiveAdaptiveRLOuterEvidenceV3:
    evidence_v2: MassiveAdaptiveRLOuterEvidenceV2
    authenticated_folds: tuple[MassiveAdaptiveAuthenticatedRLOuterFoldV3, ...]
    authenticated_fold_inventory_sha256: str
    source_data_qualified: bool
    semantic_receipt_sha256: str
    profitability_reporting_authorized: bool = False
    lockbox_access_authorized: bool = False
    protocol_receipt_sha256: str = MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256
    specification_sha256: str = MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SPEC_SHA256
    implementation_source_sha256: str = (
        MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SOURCE_SHA256
    )
    schema: str = MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SCHEMA

    def semantic_unsigned(self) -> dict[str, object]:
        return {
            "schema": self.schema,
            "evidence_v2_receipt_sha256": self.evidence_v2.semantic_receipt_sha256,
            "authenticated_fold_inventory_sha256": (
                self.authenticated_fold_inventory_sha256
            ),
            "source_data_qualified": self.source_data_qualified,
            "profitability_reporting_authorized": False,
            "lockbox_access_authorized": False,
            "protocol_receipt_sha256": self.protocol_receipt_sha256,
            "specification_sha256": self.specification_sha256,
            "implementation_source_sha256": self.implementation_source_sha256,
        }

    def validate(self) -> None:
        self.evidence_v2.validate()
        for fold in self.authenticated_folds:
            fold.validate()
        if (
            self.schema != MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SCHEMA
            or tuple(fold.fold_index for fold in self.authenticated_folds)
            != tuple(range(len(self.authenticated_folds)))
            or self.authenticated_fold_inventory_sha256
            != semantic_sha256(
                tuple(fold.semantic_receipt_sha256 for fold in self.authenticated_folds)
            )
            or self.source_data_qualified
            != all(fold.source_data_qualified for fold in self.authenticated_folds)
            or self.profitability_reporting_authorized
            or self.lockbox_access_authorized
            or self.semantic_receipt_sha256 != semantic_sha256(self.semantic_unsigned())
        ):
            raise MassiveAdaptiveRLOuterEvidenceV3Error(
                "fixed-control-authenticated outer evidence differs"
            )
        assert_no_adaptive_hold_semantics(self.semantic_unsigned())


def build_massive_adaptive_rl_outer_evidence_v3(
    folds: Sequence[MassiveAdaptiveAuthenticatedRLOuterFoldV3],
) -> MassiveAdaptiveRLOuterEvidenceV3:
    ordered = tuple(sorted(folds, key=lambda value: value.fold_index))
    for fold in ordered:
        fold.validate()
    evidence_v2 = build_massive_adaptive_rl_outer_evidence_v2(
        tuple(fold.authenticated_fold_v2 for fold in ordered)
    )
    body = {
        "schema": MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SCHEMA,
        "evidence_v2": evidence_v2,
        "authenticated_folds": ordered,
        "authenticated_fold_inventory_sha256": semantic_sha256(
            tuple(fold.semantic_receipt_sha256 for fold in ordered)
        ),
        "source_data_qualified": all(fold.source_data_qualified for fold in ordered),
        "profitability_reporting_authorized": False,
        "lockbox_access_authorized": False,
        "protocol_receipt_sha256": MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256,
        "specification_sha256": MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SPEC_SHA256,
        "implementation_source_sha256": MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V3_SOURCE_SHA256,
    }
    provisional = MassiveAdaptiveRLOuterEvidenceV3(
        **body,  # type: ignore[arg-type]
        semantic_receipt_sha256="0" * 64,
    )
    result = MassiveAdaptiveRLOuterEvidenceV3(
        **{
            **body,
            "semantic_receipt_sha256": semantic_sha256(provisional.semantic_unsigned()),
        }  # type: ignore[arg-type]
    )
    result.validate()
    return result


