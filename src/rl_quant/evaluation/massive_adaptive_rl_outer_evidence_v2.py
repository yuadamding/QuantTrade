"""Checkpoint-authenticated outer evidence for adaptive RL.

V1 statistically aggregates economic folds.  V2 adds the missing provenance
gate: every primary fold must be replayed by a fold-bound frozen actor through
``MassiveAdaptiveRLOuterRolloutAuthorityV1`` before it can enter aggregation.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from rl_quant.evaluation.massive_adaptive_rl_outer_evidence_v1 import (
    MassiveAdaptiveRLOuterCostFoldV1,
    MassiveAdaptiveRLOuterEvidenceV1,
    build_massive_adaptive_rl_outer_evidence_v1,
)
from rl_quant.evaluation.massive_adaptive_rl_outer_rollout_v1 import (
    MassiveAdaptiveRLOuterRolloutAuthorityV1,
)
from rl_quant.evaluation.massive_adaptive_rl_outer_cost_ladder_v1 import (
    MassiveAdaptiveRLOuterCostLadderAuthorityV1,
)
from rl_quant.protocol.canonical_artifact import file_sha256, semantic_sha256
from rl_quant.protocol.massive_adaptive_alpha_v1 import (
    MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256,
    assert_no_adaptive_hold_semantics,
)


MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V2_SCHEMA = (
    "rl-quant.massive-adaptive-authenticated-rl-outer-fold-v2"
)
MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SCHEMA = (
    "rl-quant.massive-adaptive-rl-outer-evidence-v2"
)
MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SOURCE_SHA256 = file_sha256(Path(__file__))
MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SPEC_SHA256 = semantic_sha256(
    {
        "statistics": "massive-adaptive-rl-outer-evidence-v1",
        "primary_trace": "frozen-policy-outer-rollout-authority-v1",
        "cost_stresses": "frozen-target-outer-cost-ladder-authority-v1",
        "arbitrary_transition_collections": False,
        "duration_semantics": False,
    }
)


class MassiveAdaptiveRLOuterEvidenceV2Error(ValueError):
    """An outer economic fold was not generated by its frozen actor."""


@dataclass(frozen=True, slots=True)
class MassiveAdaptiveAuthenticatedRLOuterFoldV2:
    fold_index: int
    cost_fold: MassiveAdaptiveRLOuterCostFoldV1
    outer_rollout_authority_receipt_sha256: str
    outer_rollout_receipt_sha256: str
    outer_cost_ladder_authority_receipt_sha256: str
    outer_cost_ladder_receipt_sha256: str
    primary_policy_trace_receipt_sha256: str
    source_data_qualified: bool
    semantic_receipt_sha256: str
    protocol_receipt_sha256: str = MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256
    schema: str = MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V2_SCHEMA

    def semantic_unsigned(self) -> dict[str, object]:
        return {
            "schema": self.schema,
            "fold_index": self.fold_index,
            "cost_fold_receipt_sha256": self.cost_fold.semantic_receipt_sha256,
            "outer_rollout_authority_receipt_sha256": (
                self.outer_rollout_authority_receipt_sha256
            ),
            "outer_rollout_receipt_sha256": self.outer_rollout_receipt_sha256,
            "outer_cost_ladder_authority_receipt_sha256": (
                self.outer_cost_ladder_authority_receipt_sha256
            ),
            "outer_cost_ladder_receipt_sha256": (
                self.outer_cost_ladder_receipt_sha256
            ),
            "primary_policy_trace_receipt_sha256": (
                self.primary_policy_trace_receipt_sha256
            ),
            "source_data_qualified": self.source_data_qualified,
            "protocol_receipt_sha256": self.protocol_receipt_sha256,
        }

    def validate(self) -> None:
        self.cost_fold.validate()
        if (
            self.schema != MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V2_SCHEMA
            or self.fold_index != self.cost_fold.fold_index
            or self.primary_policy_trace_receipt_sha256
            != self.cost_fold.primary_trace_receipt_sha256
            or self.semantic_receipt_sha256
            != semantic_sha256(self.semantic_unsigned())
        ):
            raise MassiveAdaptiveRLOuterEvidenceV2Error(
                "checkpoint-authenticated outer fold differs"
            )
        assert_no_adaptive_hold_semantics(self.semantic_unsigned())


def build_massive_adaptive_authenticated_rl_outer_fold_v2(
    *,
    cost_fold: MassiveAdaptiveRLOuterCostFoldV1,
    rollout_authority: MassiveAdaptiveRLOuterRolloutAuthorityV1,
    cost_ladder_authority: MassiveAdaptiveRLOuterCostLadderAuthorityV1,
) -> MassiveAdaptiveAuthenticatedRLOuterFoldV2:
    cost_fold.validate()
    rollout_authority.validate()
    cost_ladder_authority.validate()
    rollout = rollout_authority.runtime_rollout
    ladder = cost_ladder_authority.runtime_ladder
    if (
        rollout is None
        or not rollout_authority.runtime_rollout_replayed
        or ladder is None
        or not cost_ladder_authority.runtime_ladder_replayed
        or rollout.fold_index != cost_fold.fold_index
        or rollout.frozen_policy_receipt_sha256
        != cost_fold.frozen_rl_policy_receipt_sha256
        or rollout.policy_trace.semantic_receipt_sha256
        != cost_fold.primary_trace_receipt_sha256
        or rollout.decision_target_inventory_sha256
        != cost_fold.decision_target_inventory_sha256
        or ladder.outer_rollout_authority_receipt_sha256
        != rollout_authority.semantic_receipt_sha256
        or ladder.outer_rollout_receipt_sha256
        != rollout.semantic_receipt_sha256
        or ladder.frozen_policy_receipt_sha256
        != cost_fold.frozen_rl_policy_receipt_sha256
        or ladder.primary_trace.semantic_receipt_sha256
        != cost_fold.primary_trace_receipt_sha256
        or ladder.low_cost_trace.semantic_receipt_sha256
        != cost_fold.low_cost_trace_receipt_sha256
        or ladder.high_cost_trace.semantic_receipt_sha256
        != cost_fold.high_cost_trace_receipt_sha256
        or ladder.decision_target_inventory_sha256
        != cost_fold.decision_target_inventory_sha256
    ):
        raise MassiveAdaptiveRLOuterEvidenceV2Error(
            "outer cost fold is not derived from its frozen-policy rollout"
        )
    body = {
        "schema": MASSIVE_ADAPTIVE_AUTHENTICATED_RL_OUTER_FOLD_V2_SCHEMA,
        "fold_index": cost_fold.fold_index,
        "cost_fold": cost_fold,
        "outer_rollout_authority_receipt_sha256": (
            rollout_authority.semantic_receipt_sha256
        ),
        "outer_rollout_receipt_sha256": rollout.semantic_receipt_sha256,
        "outer_cost_ladder_authority_receipt_sha256": (
            cost_ladder_authority.semantic_receipt_sha256
        ),
        "outer_cost_ladder_receipt_sha256": ladder.semantic_receipt_sha256,
        "primary_policy_trace_receipt_sha256": (
            rollout.policy_trace.semantic_receipt_sha256
        ),
        "source_data_qualified": bool(
            cost_fold.source_data_qualified
            and rollout_authority.outer_evaluation_authorized
            and cost_ladder_authority.outer_evaluation_authorized
        ),
        "protocol_receipt_sha256": MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256,
    }
    result = MassiveAdaptiveAuthenticatedRLOuterFoldV2(
        **body,  # type: ignore[arg-type]
        semantic_receipt_sha256=semantic_sha256(
            {
                **body,
                "cost_fold": cost_fold.semantic_receipt_sha256,
            }
        ),
    )
    # The semantic contract uses the cost-fold receipt rather than dataclass JSON.
    result = MassiveAdaptiveAuthenticatedRLOuterFoldV2(
        **{
            **body,
            "semantic_receipt_sha256": semantic_sha256(result.semantic_unsigned()),
        }  # type: ignore[arg-type]
    )
    result.validate()
    return result


@dataclass(frozen=True, slots=True)
class MassiveAdaptiveRLOuterEvidenceV2:
    evidence_v1: MassiveAdaptiveRLOuterEvidenceV1
    authenticated_folds: tuple[MassiveAdaptiveAuthenticatedRLOuterFoldV2, ...]
    authenticated_fold_inventory_sha256: str
    source_data_qualified: bool
    semantic_receipt_sha256: str
    profitability_reporting_authorized: bool = False
    lockbox_access_authorized: bool = False
    protocol_receipt_sha256: str = MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256
    specification_sha256: str = MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SPEC_SHA256
    implementation_source_sha256: str = (
        MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SOURCE_SHA256
    )
    schema: str = MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SCHEMA

    def semantic_unsigned(self) -> dict[str, object]:
        return {
            "schema": self.schema,
            "evidence_v1_receipt_sha256": self.evidence_v1.semantic_receipt_sha256,
            "authenticated_fold_inventory_sha256": (
                self.authenticated_fold_inventory_sha256
            ),
            "source_data_qualified": self.source_data_qualified,
            "profitability_reporting_authorized": False,
            "lockbox_access_authorized": False,
            "protocol_receipt_sha256": self.protocol_receipt_sha256,
            "specification_sha256": self.specification_sha256,
            "implementation_source_sha256": self.implementation_source_sha256,
        }

    def validate(self) -> None:
        self.evidence_v1.validate()
        for fold in self.authenticated_folds:
            fold.validate()
        if (
            self.schema != MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SCHEMA
            or tuple(fold.fold_index for fold in self.authenticated_folds)
            != tuple(range(len(self.authenticated_folds)))
            or self.authenticated_fold_inventory_sha256
            != semantic_sha256(
                tuple(fold.semantic_receipt_sha256 for fold in self.authenticated_folds)
            )
            or self.source_data_qualified
            != all(fold.source_data_qualified for fold in self.authenticated_folds)
            or self.profitability_reporting_authorized
            or self.lockbox_access_authorized
            or self.semantic_receipt_sha256
            != semantic_sha256(self.semantic_unsigned())
        ):
            raise MassiveAdaptiveRLOuterEvidenceV2Error(
                "checkpoint-authenticated outer evidence differs"
            )
        assert_no_adaptive_hold_semantics(self.semantic_unsigned())


def build_massive_adaptive_rl_outer_evidence_v2(
    folds: Sequence[MassiveAdaptiveAuthenticatedRLOuterFoldV2],
) -> MassiveAdaptiveRLOuterEvidenceV2:
    ordered = tuple(sorted(folds, key=lambda value: value.fold_index))
    for fold in ordered:
        fold.validate()
    evidence_v1 = build_massive_adaptive_rl_outer_evidence_v1(
        tuple(fold.cost_fold for fold in ordered)
    )
    body = {
        "schema": MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SCHEMA,
        "evidence_v1": evidence_v1,
        "authenticated_folds": ordered,
        "authenticated_fold_inventory_sha256": semantic_sha256(
            tuple(fold.semantic_receipt_sha256 for fold in ordered)
        ),
        "source_data_qualified": all(fold.source_data_qualified for fold in ordered),
        "profitability_reporting_authorized": False,
        "lockbox_access_authorized": False,
        "protocol_receipt_sha256": MASSIVE_ADAPTIVE_ALPHA_V1_RECEIPT_SHA256,
        "specification_sha256": MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SPEC_SHA256,
        "implementation_source_sha256": (
            MASSIVE_ADAPTIVE_RL_OUTER_EVIDENCE_V2_SOURCE_SHA256
        ),
    }
    provisional = MassiveAdaptiveRLOuterEvidenceV2(
        **body,  # type: ignore[arg-type]
        semantic_receipt_sha256="0" * 64,
    )
    result = MassiveAdaptiveRLOuterEvidenceV2(
        **{
            **body,
            "semantic_receipt_sha256": semantic_sha256(provisional.semantic_unsigned()),
        }  # type: ignore[arg-type]
    )
    result.validate()
    return result


